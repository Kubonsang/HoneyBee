import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

const packages = [
  "apps/desktop/package.json",
  "apps/cli/package.json",
  "packages/core/package.json",
];
const compatibilityPath = "apps/desktop/resources/component-compatibility-v1.json";
const cliPath = "apps/cli/src/product-version.ts";
const json = (value) => JSON.stringify(value, null, 2) + "\n";

/** Pure projection: component versions and payload identities are deliberately untouched. */
export function productVersionFiles(rootPackage, manifests, compatibility) {
  const version = rootPackage.version;
  assert(
    typeof version === "string" && /^\d+\.\d+\.\d+(?:-(?:beta|rc)\.\d+)?$/u.test(version),
    "Invalid product version",
  );
  assert.equal(manifests.length, packages.length);
  const files = new Map(
    packages.map((name, index) => [name, json({ ...manifests[index], version })]),
  );
  const next = JSON.parse(JSON.stringify(compatibility));
  next.honeybeeVersion = version;
  for (const entries of [next.workspaceStorage, next.testplay])
    for (const entry of entries ?? []) entry.honeybeeVersion = version;
  files.set(compatibilityPath, json(next));
  files.set(
    cliPath,
    `// Generated by scripts/installation/product-version.mjs.\nexport const WORKSPACE_CLI_VERSION = ${JSON.stringify(version)};\n`,
  );
  return files;
}

export async function synchronizeProductVersion(root, { check = false } = {}) {
  const readJson = async (name) => JSON.parse(await readFile(path.join(root, name), "utf8"));
  const files = productVersionFiles(
    await readJson("package.json"),
    await Promise.all(packages.map(readJson)),
    await readJson(compatibilityPath),
  );
  const changed = [];
  for (const [name, expected] of files) {
    const target = path.join(root, name);
    const actual = await readFile(target, "utf8").catch((error) => {
      if (error.code === "ENOENT") return "";
      throw error;
    });
    if (actual.replaceAll("\r\n", "\n") === expected) continue;
    changed.push(name);
    if (!check) await writeFile(target, expected);
  }
  assert(
    !check || changed.length === 0,
    `Product versions differ; run pnpm version:sync: ${changed.join(", ")}`,
  );
  return changed;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  assert(process.argv.slice(2).every((arg) => arg === "--check"));
  await synchronizeProductVersion(path.resolve(import.meta.dirname, "../.."), {
    check: process.argv.includes("--check"),
  });
}
